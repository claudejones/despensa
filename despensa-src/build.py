#!/usr/bin/env python3
"""Despensa build — assembles the five sources into index.html.

Rebuilt on 14 Nov after the working container was replaced. The sources were
recovered by splitting the deployed index.html back apart; CAT_FP and SEED_FP
came out matching the deployed build exactly (147851e8 / 49f6f833), which is
what proves the split was faithful rather than approximately right.

The fingerprints are hashes of catalogue.js and seed-trips.js. They are the
gate: a typed data version number is the bug this replaced, twice.
"""
import hashlib, pathlib, re, sys, json

SRC = pathlib.Path(__file__).resolve().parent
OUT = SRC.parent / "index.html"

shell = (SRC / "shell.html").read_text()
icons = (SRC / "icons.js").read_text()
cat   = (SRC / "catalogue.js").read_text()
seed  = (SRC / "seed-trips.js").read_text()
app   = (SRC / "app.js").read_text()

cat_fp  = hashlib.sha256(cat.encode()).hexdigest()[:8]
seed_fp = hashlib.sha256(seed.encode()).hexdigest()[:8]

# ---------------------------------------------------------------------------
# The app must actually consult the fingerprints, or they are decoration.
for needed in ("CAT_FP", "SEED_FP"):
    if needed not in app:
        sys.exit("BUILD FAILED: app.js never reads %s — the gate is dead code" % needed)

# sw.js must stay version-free: a versioned cache name strands phones.
swtext = (SRC.parent / "sw.js").read_text()
if re.search(r'CACHE\s*=\s*"despensa[-.]', swtext):
    sys.exit("BUILD FAILED: sw.js has a versioned cache name again")
if "/sync/" not in swtext:
    sys.exit("BUILD FAILED: sw.js lost the /sync/ carve-out")

# ---------------------------------------------------------------------------
# Price history must be well formed.
#
# The 14 Oct reconciliation appended seven points as a NESTED array in the
# third slot — ["2026-09-20",30.74,["2026-10-14",20.80]]. seed() reads h[0],
# h[1] and h[2], so every one of those points was silently swallowed: valid
# JavaScript, valid-looking source, and the data never reached a phone. Only
# a structural check catches that class of error; reading it is how it got
# through in the first place.
#
# A point is [date, price] or [date, price, shop].
_shops = set(re.findall(r'\{id:"([^"]+)",\s*name:"[^"]*",\s*active:', cat))
if not _shops:
    sys.exit("BUILD FAILED: no shops parsed out of catalogue.js — the history "
             "check cannot validate shop ids")
_bad = []
for _m in re.finditer(r'hist:(\[.*?\])\s*\}', cat, re.S):
    _lit = _m.group(1)
    _ctx = cat[max(0, _m.start() - 240):_m.start()]
    _name = (re.findall(r'es:"((?:[^"\\]|\\.)*)"', _ctx) or ["?"])[-1]
    try:
        _pts = json.loads(_lit)
    except ValueError as e:
        _bad.append("%s: history is not parseable (%s)" % (_name, e)); continue
    _last = ""
    for _p in _pts:
        if not isinstance(_p, list) or len(_p) not in (2, 3):
            _bad.append("%s: %r is not [date, price] or [date, price, shop]" % (_name, _p)); continue
        if not (isinstance(_p[0], str) and re.fullmatch(r"\d{4}-\d{2}-\d{2}", _p[0])):
            _bad.append("%s: %r has no ISO date in slot 0" % (_name, _p)); continue
        if not isinstance(_p[1], (int, float)):
            _bad.append("%s: %r has no number in slot 1" % (_name, _p)); continue
        if len(_p) == 3 and not (isinstance(_p[2], str) and _p[2] in _shops):
            _bad.append("%s: %r — slot 2 must be a shop id, one of %s"
                        % (_name, _p, sorted(_shops))); continue
        if _p[0] < _last:
            _bad.append("%s: %s comes after %s — history must run forwards, or "
                        "the newest price is not the last one" % (_name, _p[0], _last))
        _last = _p[0]
if _bad:
    sys.exit("BUILD FAILED: malformed price history\n  " + "\n  ".join(_bad))

# ---------------------------------------------------------------------------
GEN = ('/* Generated by build.py — do not edit. Fingerprints are hashes of\n'
       '   catalogue.js and seed-trips.js, so they cannot drift from the data. */\n'
       'var CAT_FP  = "%s";\n'
       'var SEED_FP = "%s";' % (cat_fp, seed_fp))

out = (shell
       .replace("/*__ICONS__*/", icons.rstrip("\n") + "\n")
       .replace("/*__CATALOGUE__*/",
                cat.rstrip("\n") + "\n\n" + seed.rstrip("\n") + "\n\n" + GEN + "\n")
       .replace("/*__APP__*/", app.rstrip("\n") + "\n"))

prev = OUT.read_text() if OUT.exists() else ""
OUT.write_text(out)

def ver(t):
    m = re.search(r'APP_VERSION = "([^"]+)"', t)
    return m.group(1) if m else "?"
def fp(t, which):
    m = re.search(r'var %s\s*= "([^"]+)"' % which, t)
    return m.group(1) if m else "?"

print("  app       %-12s %s" % (ver(out), "unchanged" if ver(prev)==ver(out) else "(was %s)" % ver(prev)))
print("  catalogue fp %s  %s" % (cat_fp, "unchanged" if fp(prev,"CAT_FP")==cat_fp else "(was %s)" % fp(prev,"CAT_FP")))
print("  seed      fp %s  %s" % (seed_fp, "unchanged" if fp(prev,"SEED_FP")==seed_fp else "(was %s)" % fp(prev,"SEED_FP")))
print("  index.html %d bytes" % len(out.encode()))
if fp(prev,"CAT_FP") != cat_fp:
    print("  NOTE: cat data changed — installed phones will rebuild it on next load.")
